"""Export existing Filo branding for inline email. Requires local Pillow."""
import base64
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

APP = Path(__file__).resolve().parents[2]
DEST = APP / "backend/supabase/functions/_shared/otp_email_assets.ts"
SCALE = 2
INK = (20, 66, 58)
PRIMARY = (35, 107, 87)
MINT = (220, 233, 218)


def png(image):
    output = BytesIO()
    image.save(output, format="PNG", optimize=True)
    return output.getvalue()


def path(start, curves):
    points = [start]
    for a, b, end in curves:
        x, y = points[-1]
        for step in range(1, 41):
            t = step / 40
            u = 1 - t
            points.append((u**3*x + 3*u*u*t*a[0] + 3*u*t*t*b[0] + t**3*end[0],
                           u**3*y + 3*u*u*t*a[1] + 3*u*t*t*b[1] + t**3*end[1]))
    return points


def render_art():
    font = ImageFont.truetype(str(APP / "frontend/assets/fonts/Nunito.ttf"), 64)
    font.set_variation_by_axes([900])
    bounds = font.getbbox("filo")
    wordmark = Image.new("RGBA", (bounds[2] - bounds[0] + 4, bounds[3] - bounds[1] + 4))
    ImageDraw.Draw(wordmark).text((2-bounds[0], 2-bounds[1]), "filo", font=font, fill=INK)

    # Bake the backing into the image so client color inversion cannot separate it.
    brand = Image.new("RGBA", (288, 112))
    ImageDraw.Draw(brand).rounded_rectangle((0, 0, 287, 111), radius=24, fill=MINT)
    logo = Image.open(APP / "frontend/assets/brand/logo-mark-light.png").convert("RGBA")
    logo = logo.crop(logo.getbbox())
    wordmark = wordmark.crop(wordmark.getbbox())
    logo.thumbnail((64, 64), Image.Resampling.LANCZOS)
    gap = 16
    group_width = logo.width + gap + wordmark.width
    start = (brand.width - group_width) // 2
    assert start >= 24 and abs(start - (brand.width - start - group_width)) <= 1
    brand.alpha_composite(logo, (start, (brand.height-logo.height)//2))
    brand.alpha_composite(wordmark, (start+logo.width+gap, (brand.height-wordmark.height)//2))

    # Same verification curves; transparent pixels avoid a fixed light/dark matte.
    leaves = Image.new("RGBA", (480*SCALE, 160*SCALE))
    draw = ImageDraw.Draw(leaves)

    def fill(points, color, alpha):
        tint = (*color, round(255*alpha))
        draw.polygon([(round(x*SCALE), round((y-480)*SCALE)) for x, y in points], fill=tint)

    for start, curves, alpha in [
        ((0, .85), [((.22, .8), (.42, .94), (.65, .9)), ((.85, .86), (.95, .86), (1, .87))], .65),
        ((0, .91), [((.3, .85), (.55, .99), (.77, .93)), ((.9, .91), (.96, .9), (1, .9))], .7),
    ]:
        points = path(start, curves) + [(1, 1), (0, 1)]
        fill([(x*480, y*640) for x, y in points], MINT, alpha*.45)

    for x, y, scale in [(480*.09, 640*.86, 1), (480*.94, 640*.93, -.75)]:
        for start, curves in [
            ((0, 0), [((-30, -12), (-30, -37), (-24, -38)), ((-7, -35), (-4, -15), (0, 0))]),
            ((2, -20), [((-6, -41), (5, -65), (16, -67)), ((23, -48), (14, -29), (2, -20))]),
            ((2, -4), [((8, -25), (25, -32), (37, -27)), ((31, -9), (15, -3), (2, -4))]),
        ]:
            fill([(x+px*scale, y+py*abs(scale)) for px, py in path(start, curves)], PRIMARY, .4)
        draw.line([(round((x+px*scale)*SCALE), round((y+py*abs(scale)-480)*SCALE))
                   for px, py in path((0, 2), [((-.67, -7.33), (1, -18.67), (5, -32))])],
                  fill=(*PRIMARY, 102), width=3)

    assert brand.getpixel((144, 10)) == (*MINT, 255), "Brand backing must stay opaque"
    assert leaves.getpixel((0, 0))[3] == 0, "Footer must have no opaque matte"
    return png(brand), png(leaves)


def export():
    brand, leaves = render_art()
    assets = {"brand": brand, "leaves": leaves}
    assert all(value.startswith(b"\x89PNG\r\n\x1a\n") for value in assets.values())
    assert sum(map(len, assets.values())) < 100_000, "Keep verification email artwork small"
    DEST.write_text("// Generated by backend/tools/export_otp_email_assets.py; do not edit.\n"
                    + "export const otpEmailAssets = {\n"
                    + "".join(f'  {name}: "{base64.b64encode(value).decode()}",\n' for name, value in assets.items())
                    + "};\n", encoding="utf-8")
    print(f"Exported {len(assets)} inline assets ({sum(map(len, assets.values()))} PNG bytes).")


if __name__ == "__main__":
    export()
